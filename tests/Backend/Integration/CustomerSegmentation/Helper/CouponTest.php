declare(strict_types=1);

uses(Tests\MahoBackendTestCase::class);

beforeEach(function () {
    $this->rule = Mage::getModel('salesrule/rule')
        ->setName('Automation coupon owner ' . uniqid())
        ->setIsActive()
        ->setWebsiteIds([1])
        ->setCustomerGroupIds([0, 1])
        ->setCouponType(Mage_SalesRule_Model_Rule::COUPON_TYPE_SPECIFIC)
        ->setUseAutoGeneration(true)
        ->setSimpleAction('by_percent')
        ->setDiscountAmount(10)
        ->save();

    $customerIds = Mage::getResourceModel('customer/customer_collection')->getAllIds(2);
    [$this->customerA, $this->customerB] = array_map(intval(...), $customerIds);
});

afterEach(function () {
    $this->rule->delete();
});

test('a customer gets back their own unused coupon and never the coupon of another customer', function () {
    $helper = Mage::helper('customersegmentation/coupon');
    $ruleId = (int) $this->rule->getId();

    // The prefix puts the ID of customer B in the code of customer A.
    $codeA = $helper->generateCustomerCoupon($this->customerA, $ruleId, 'OWN' . $this->customerB, 30);
    $codeAAgain = $helper->generateCustomerCoupon($this->customerA, $ruleId, 'OWN', 30);
    $codeB = $helper->generateCustomerCoupon($this->customerB, $ruleId, 'OWN', 30);

    expect($codeA)->toContain((string) $this->customerB)
        ->and($codeAAgain)->toBe($codeA)
        ->and($codeB)->not->toBeNull()
        ->and($codeB)->not->toBe($codeA);
});

test('an automation coupon with no recorded owner is not given to a customer', function () {
    $legacyCode = 'LEGACY' . $this->customerB . strtoupper(bin2hex(random_bytes(3)));
    Mage::getModel('salesrule/coupon')
        ->setRuleId((int) $this->rule->getId())
        ->setCode($legacyCode)
        ->setUsageLimit(1)
        ->setUsagePerCustomer(1)
        ->setType(Mage_SalesRule_Helper_Coupon::COUPON_TYPE_SPECIFIC_AUTOGENERATED)
        ->save();

    $code = Mage::helper('customersegmentation/coupon')
        ->generateCustomerCoupon($this->customerB, (int) $this->rule->getId(), 'OWN', 30);

    expect($code)->not->toBeNull()
        ->and($code)->not->toBe($legacyCode);
});
